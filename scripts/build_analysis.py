def load_responses():
    out = []
    for rp in sorted(RAW_DIR.glob('*.json'), key=lambda p: int(p.stem.split('_')[0])):
        with open(rp, encoding='utf-8') as f:
            raw = json.load(f)
        pp = PROCESSED_DIR / rp.name
        raw['_analysis'] = None
        if pp.exists():
            with open(pp, encoding='utf-8') as f:
                raw['_analysis'] = json.load(f).get('analysis')
        out.append(raw)
    return out

def write_data_js(responses, ts):
    text = ('// Auto-generated by scripts/build_analysis.py\n'
            '// Snapshot: ' + ts + '\n'
            'const SURVEY_DATA = ' + json.dumps(responses, ensure_ascii=False, indent=2) + ';\n')
    (OUT_DIR / 'data.js').write_text(text, encoding='utf-8')

