def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--data-only', action='store_true',
                        help='Regenerate data.js only; leave all HTML files untouched.')
    args = parser.parse_args()

    ts = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    responses = load_responses()
    write_data_js(responses, ts)
    print('data.js written ({} responses)'.format(len(responses)))

    if args.data_only:
        print('\nDone (data only). HTML files were not modified.')
        return

    pages = {
        'index.html':    INDEX_JS,
        'section1.html': SECTION1_JS,
        'section2.html': SECTION2_JS,
        'section3.html': SECTION3_JS,
        'section4.html': SECTION4_JS,
        'section5.html': SECTION5_JS,
        'meta.html':     META_JS,
        'analysis.html': ANALYSIS_JS,
    }
    for filename, body_js in pages.items():
        html = page(filename, body_js, ts)
        (OUT_DIR / filename).write_text(html, encoding='utf-8')
        print('written: analysis/' + filename)

    print('\nDone. Open analysis/index.html in your browser.')

if __name__ == '__main__':
    main()
